def ft_of(when):
    """지역 시각(naive) → FILETIME(정수 연산 — 부동소수 오차 없이)"""
    d = when.astimezone(UTC) - datetime(1601, 1, 1, tzinfo=UTC)
    return (d.days * 86400 + d.seconds) * 10 ** 7 + d.microseconds * 10


def ua_val(runs, focus=0, ms=0, when=None):
    """Win7+ UserAssist 값 72바이트 — 실행 @4 · 포커스 횟수 @8 · 포커스 ms @12 · 마지막 실행 FILETIME @60"""
    return struct.pack("<IIII", 0, runs, focus, ms) + b"\0" * 44 + struct.pack("<QI", ft_of(when) if when else 0, 0)


class FakeReg:
    """values·subkeys 두 메서드만 — {(하이브, 경로): [(이름, 값, 형식)]} · denied 는 PermissionError"""

    def __init__(self, keys, denied=()):
        self.keys = {(h, p.lower()): v for (h, p), v in keys.items()}
        self.denied = {(h, p.lower()) for h, p in denied}

    def values(self, hive, path):
        k = (hive, path.lower())
        if k in self.denied:
            raise PermissionError(path)
        if k not in self.keys:
            raise FileNotFoundError(path)
        return list(self.keys[k])

    def subkeys(self, hive, path):
        k = (hive, path.lower())
        if k in self.denied:
            raise PermissionError(path)
        pre = path.lower() + "\\"
        subs = sorted({kp[len(pre):].split("\\")[0] for (h, kp) in self.keys if h == hive and kp.startswith(pre)})
        if not subs and k not in self.keys:
            raise FileNotFoundError(path)
        return subs


