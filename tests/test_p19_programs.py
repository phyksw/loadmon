def write_snap(dirp, when, items, pc="pcA", sources=None):
    os.makedirs(dirp, exist_ok=True)
    with open(os.path.join(dirp, f"snap_{when:%Y%m%d_%H%M%S}.json"), "w", encoding="utf-8") as f:
        json.dump({"v": 1, "taken": when.strftime("%Y-%m-%d %H:%M:%S"), "pc": pc,
                   "sources": sources or {"ua": True, "fu": True, "bam": False, "bam_why": "denied"},
                   "items": items}, f, ensure_ascii=False)


def it(exe, cls, run=0, ms=0, last=None, vf="", **kw):
    d = {"exe": exe, "cls": cls}
    if vf:
        d["vf"] = vf
    if run:
        d["ua_run"] = run
    if ms:
        d["ua_ms"] = ms
    if last:
        d["ua_last"] = last
    d.update(kw)
    return d


def write_files(root, rows):
    os.makedirs(os.path.join(root, "files"), exist_ok=True)
    with open(os.path.join(root, "files", "files.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["mtime", "ext", "size_kb", "folder", "name", "author", "total_time", "revision"])
        for r in rows:
            w.writerow(list(r) + [""] * (8 - len(r)))


